"""Run the analyzer on the demonstration article and write samples/DEMO_RESULTS.md.

Usage (from repo root):  python scripts/run_demo.py
Uses whatever LLM/search providers are configured in the environment; with none
configured the output is rule-based only (as committed).
"""
import asyncio
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "backend"))

from app.engine import analyze  # noqa: E402
from app.models import AnalyzeRequest  # noqa: E402

LABEL = {"factuality": "Factuality", "quality": "Writing quality", "intent": "Search intent", "brand": "Brand voice"}


def cell(s: str) -> str:
    return s.replace("|", "\\|").replace("\n", " ")


def main() -> None:
    text = (ROOT / "samples" / "demo_article.md").read_text()
    brief = json.loads((ROOT / "samples" / "demo_brief.json").read_text())
    note = brief.pop("_note")
    r = asyncio.run(analyze(AnalyzeRequest(text=text, **brief)))
    L = [
        "# Demo results (actual tool output)",
        "",
        f"> **{note}**",
        "",
        "Generated by `python scripts/run_demo.py` against `samples/demo_article.md` with the brief in `samples/demo_brief.json`.",
        "",
        f"- AI review: **{r.ai.status}**. {r.ai.message}",
        f"- Source verification: {r.verification_provider}",
        f"- Score: **{r.summary.score}/100**. {r.summary.headline}",
        f"- {r.summary.score_explanation}",
        f"- Findings by category: " + ", ".join(f"{LABEL[k]} {v}" for k, v in r.summary.by_category.items()),
        f"- Findings by severity: " + ", ".join(f"{k} {v}" for k, v in r.summary.by_severity.items()),
        "",
        "| # | Category | Severity | Conf. | Source | Finding | Exact evidence | Suggested change |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for i, f in enumerate(r.findings, 1):
        ev = f"“{f.evidence.text[:110]}{'…' if len(f.evidence.text) > 110 else ''}” (chars {f.evidence.start}–{f.evidence.end})" if f.evidence else f"_{f.evidence_note}_"
        repl = f.suggestion.replacement
        change = ("remove" if repl == "" else f"→ “{repl}”") if repl is not None else f.suggestion.note
        L.append(f"| {i} | {LABEL[f.category]} | {f.severity} | {f.confidence} | {'AI' if f.origin == 'ai' else 'rule'} | {cell(f.title)} | {cell(ev)} | {cell(change[:160])} |")
    L += ["", "Every factuality finding above has verification status **Needs verification**; no sources were retrieved or invented.", "", "## Limitations", ""]
    L += [f"- {x}" for x in r.limitations]
    (ROOT / "samples" / "DEMO_RESULTS.md").write_text("\n".join(L) + "\n")
    print(f"Wrote samples/DEMO_RESULTS.md with {len(r.findings)} findings.")


if __name__ == "__main__":
    main()
